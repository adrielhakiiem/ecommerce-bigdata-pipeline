"""Load a bounded event sample into HBase for low-latency lookups."""

from __future__ import annotations

import argparse
import logging
import subprocess
import tempfile
from pathlib import Path

from pyspark.sql import SparkSession
from pyspark.sql.functions import concat_ws

LOGGER = logging.getLogger(__name__)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", default="ecommerce_dw")
    parser.add_argument("--table", default="sales_fact")
    parser.add_argument("--hbase-table", default="realtime_sales")
    parser.add_argument("--limit", type=int, default=10_000)
    parser.add_argument("--hbase-command", default="hbase")
    return parser.parse_args()


def hbase_quote(value: object) -> str:
    """Quote values for HBase shell while escaping shell metacharacters."""
    text = str(value).replace("\\", "\\\\").replace("'", "\\'")
    return f"'{text}'"


def build_insert_script(rows: list[dict[str, object]], table: str) -> str:
    commands = ["# Generated by load_to_hbase.py"]
    for row in rows:
        rowkey = hbase_quote(row["rowkey"])
        event = hbase_quote(row["event"])
        commands.append(f"put {hbase_quote(table)}, {rowkey}, 'info:event', {event}")
    commands.append("exit")
    return "\n".join(commands) + "\n"


def run(args: argparse.Namespace) -> None:
    if args.limit < 1:
        raise ValueError("--limit must be greater than zero")

    spark = (
        SparkSession.builder.appName("Load_to_HBase")
        .enableHiveSupport()
        .getOrCreate()
    )
    try:
        query = f"""
            SELECT timestamp, visitorid, event, itemid
            FROM `{args.database}`.`{args.table}`
            ORDER BY event_date DESC, timestamp DESC
            LIMIT {args.limit}
        """
        rows = (
            spark.sql(query)
            .withColumn("rowkey", concat_ws("_", "timestamp", "visitorid", "itemid"))
            .select("rowkey", "event")
            .toLocalIterator()
        )
        records = [row.asDict() for row in rows]
        script = build_insert_script(records, args.hbase_table)

        with tempfile.NamedTemporaryFile(
            mode="w", suffix=".hbase", prefix="ecommerce-", delete=False
        ) as script_file:
            script_file.write(script)
            script_path = Path(script_file.name)

        try:
            LOGGER.info("Loading %d records into HBase table %s", len(records), args.hbase_table)
            subprocess.run(
                [args.hbase_command, "shell", str(script_path)],
                check=True,
            )
        finally:
            script_path.unlink(missing_ok=True)
    finally:
        spark.stop()


if __name__ == "__main__":
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s - %(message)s",
    )
    run(parse_args())
